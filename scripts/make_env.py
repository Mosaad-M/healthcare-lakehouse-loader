"""Create or complete .env: values from .env.example, plus fresh local secrets.

    python3 scripts/make_env.py      # run by every `make` target; idempotent

Never overwrites a value that is already set: it only adds what is missing (so a .env from an
older checkout gains the secrets added since). Stdlib only. These keys protect synthetic data in a
local stack; on AWS the master key lives in KMS and the pepper in Secrets Manager.
"""
import base64
import os
import pathlib

import secrets


def key() -> str:
    return base64.b64encode(os.urandom(32)).decode()


def password() -> str:
    return secrets.token_hex(16)


GENERATED = {
    "LOADER_MASTER_KEY": (key, "Losing it makes every encrypted identifier unreadable."),
    "LOADER_IDENTITY_PEPPER": (key, "Changing it splits every person into new subjects."),
    "PREFECT_API_AUTH_STRING": (lambda: f"lakehouse:{password()}", "Prefect API basic auth (server, worker, flows, tests)."),
    "DORIS_ROOT_PASSWORD": (password, "Doris administrator (setup only)."),
    "DORIS_REFRESHER_PASSWORD": (password, "Doris user serving_refresher: rebuilds the serving copies (flow runs)."),
    "DORIS_ANALYST_PASSWORD": (password, "Doris user analyst: de-identified copies."),
    "DORIS_ANALYST_MA_PASSWORD": (password, "Doris user analyst_ma: de-identified copies, MA rows only."),
    "DORIS_CARE_TEAM_PASSWORD": (password, "Doris user care_team: member mart without identifier columns."),
    "LOADER_SOURCE_SECRET_ACME_PARTNER_API": (password, "Token for the mock partner API (contracts/acme_encounters.yaml)."),
}

env = pathlib.Path(".env")
lines = env.read_text().rstrip("\n").splitlines() if env.exists() else []
present = {line.split("=", 1)[0].strip() for line in lines if "=" in line and not line.lstrip().startswith("#")}
added = []
for line in pathlib.Path(".env.example").read_text().splitlines():
    if "=" in line and not line.lstrip().startswith("#") and line.split("=", 1)[0].strip() not in present:
        lines.append(line)
        added.append(line.split("=", 1)[0])
for name, (make, note) in GENERATED.items():
    if name not in present:
        lines += [f"# Generated by scripts/make_env.py. {note}", f"{name}={make()}"]
        added.append(name)
if added or not env.exists():
    env.write_text("\n".join(lines) + "\n")
    env.chmod(0o600)
    print(f".env: added {', '.join(added)}")
